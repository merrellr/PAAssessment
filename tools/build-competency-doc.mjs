// Writes docs/competency-model.md from competencies-core.js: the competencies, what each looks like at the four
// levels, and the lessons that build each one (with how many practice questions count toward it). For review.
//   node tools/build-competency-doc.mjs           write it
//   node tools/build-competency-doc.mjs --check   fail if it is out of date
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
globalThis.window = globalThis;
for (const f of ['company-core.js', 'roles-core.js', 'coach-bank.js', 'coach-charts.js', 'competencies-core.js', 'shape-core.js']) eval(fs.readFileSync(path.join(root, f), 'utf8'));
const K = globalThis.CompetencyCore, B = globalThis.CoachBank, Q = B.questions.concat(globalThis.CoachCharts.questions);
const AREA = { discovery: 'Customer & Market Discovery', strategy: 'Product Strategy & Roadmapping', prioritization: 'Prioritization & Trade-offs', execution: 'Execution & Delivery',
  stakeholder: 'Stakeholder Communication & Influence', aiIndividual: 'AI Fluency — Individual', aiOrg: 'AI Fluency — Organizational' };
const LEVEL = { novice: 'Limited', moderate: 'Moderate', experienced: 'Lots of', advanced: 'Advanced' };
const lessonsFor = {};
Object.keys(K.LESSONS).forEach(cid => K.LESSONS[cid].forEach((tags, i) => tags.forEach(k => {
  const l = B.lessons[cid][i], tier = cid.split('-').pop();
  (lessonsFor[k] = lessonsFor[k] || []).push(AREA[cid.replace(/-[a-z]+$/, '')].split(' ')[0] + ' · ' + LEVEL[tier] + ': ' + l.title.replace(/^Lesson \d+:\s*/, ''));
})));
const qCount = {}; Q.forEach(q => K.forQuestion(q).forEach(k => { qCount[k] = (qCount[k] || 0) + 1; }));
let md = '<!-- Generated by tools/build-competency-doc.mjs from competencies-core.js. Do not edit by hand. -->\n# The competency model\n\n' +
  '28 competencies, four under each of the seven skill areas. Each is described at the four levels the courses and role targets use ' +
  '(Limited, Moderate, Lots of and Advanced Experience). Lessons build them, and a practice question counts toward its lesson\'s competencies.\n\n' +
  'For review: is each competency right, is each level description right, and does each lesson belong where it is listed?\n';
Object.keys(AREA).forEach(a => {
  md += '\n## ' + AREA[a] + '\n';
  K.inArea(a).forEach(c => {
    md += '\n### ' + c.name + '\n\n' + c.about + '\n\n| Level | What it looks like |\n|---|---|\n' +
      c.levels.map((d, i) => '| ' + K.LEVELS[i] + ' | ' + d + ' |').join('\n') + '\n\n' +
      '**Built by ' + (lessonsFor[c.key] || []).length + ' lessons** (' + (qCount[c.key] || 0) + ' practice questions count toward it):\n\n' +
      (lessonsFor[c.key] || []).map(x => '- ' + x).join('\n') + '\n';
  });
});
// Role benchmarks: each standard role's target in every competency (bold where it differs from the role's area target)
const R = globalThis.RolesCore, S = globalThis.ShapeCore;
md += '\n## Role benchmarks\n\nEach standard role\'s target level in every competency (1 Limited, 2 Moderate, 3 Lots of, 4 Advanced). ' +
  '**Bold** marks where the role asks for more or less than its area target. A company\'s own roles take their area targets.\n\n' +
  '| Competency | ' + R.ROLES.map(r => r.title).join(' | ') + ' |\n|---|' + R.ROLES.map(() => '---').join('|') + '|\n';
const T = R.ROLES.map(r => S.targetsFor(r.targets, r.id));
K.LIST.forEach(c => { md += '| ' + c.name + ' | ' + R.ROLES.map((r, i) => { const v = T[i][c.key], a = r.targets[c.area]; return v === a ? String(v) : '**' + v + '**'; }).join(' | ') + ' |\n'; });
const out = path.join(root, 'docs', 'competency-model.md');
if (process.argv.includes('--check')) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== md) { console.error('docs/competency-model.md is out of date'); process.exit(1); } }
else { fs.writeFileSync(out, md); console.log('Wrote docs/competency-model.md'); }
