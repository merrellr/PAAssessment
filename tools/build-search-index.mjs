// Builds search-index.js (every course and lesson, for the search menu, ⌘K) and ask-index.js (the lesson text in
// short passages, for the menu's "Ask AI", loaded only when someone asks). Run after adding or editing a course in content/:
//   node tools/build-search-index.mjs
// tests/theme.test.mjs fails if either file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// The same names the dashboard uses (lms-dashboard.html: DOMAINS and TIERS).
export const DOMAINS = {
  discovery: 'Customer & Market Discovery',
  strategy: 'Product Strategy & Roadmapping',
  prioritization: 'Prioritization & Trade-offs',
  execution: 'Execution & Delivery',
  stakeholder: 'Stakeholder Communication & Influence',
  aiIndividual: 'AI Fluency — Individual',
  aiOrg: 'AI Fluency — Organizational'
};
export const TIERS = { novice: 'Limited Experience', moderate: 'Moderate Experience', experienced: 'Lots of Experience', advanced: 'Advanced Experience' };

function plain(html, max) {
  const t = String(html || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
  return max && t.length > max ? t.slice(0, max).replace(/\s\S*$/, '') + '…' : t;
}

function loadContent() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const f of fs.readdirSync(path.join(root, 'content')).filter(f => f.endsWith('.js')).sort()) {
    vm.runInContext(fs.readFileSync(path.join(root, 'content', f), 'utf8'), sandbox, { filename: f });
  }
  return { content: sandbox.window.CONTENT_OVERRIDES || {}, framework: sandbox.window.FRAMEWORK_DATA || {} };
}

export function buildIndex() {
  const { content, framework } = loadContent();
  const items = [];
  for (const d of Object.keys(DOMAINS)) {
    const fw = framework[d] || {};
    items.push({ k: 'framework', t: DOMAINS[d], s: 'Skill area in the framework', u: 'framework.html#' + d, x: plain(fw.description, 300) });
    for (const tier of Object.keys(TIERS)) {
      const id = d + '-' + tier;
      const c = content[id];
      if (!c || !Array.isArray(c.lessons)) continue;
      const course = DOMAINS[d] + ' · ' + TIERS[tier];
      items.push({ k: 'course', t: course, s: c.lessons.length + ' lessons', u: 'lesson.html?course=' + id + '&lesson=1',
        x: c.lessons.map(l => l.title).join(' · ') });
      c.lessons.forEach((l, i) => {
        items.push({ k: 'lesson', t: String(l.title || 'Lesson ' + (i + 1)).replace(/^Lesson \d+:\s*/, ''), s: course + ' · Lesson ' + (i + 1),
          u: 'lesson.html?course=' + id + '&lesson=' + (i + 1), x: plain(l.body, 360) });
      });
    }
  }
  return items;
}

export function renderIndex(items) {
  return '/* Generated by tools/build-search-index.mjs from content/. Do not edit by hand. */\n' +
    'window.PA_SEARCH = ' + JSON.stringify(items) + ';\n';
}

// Everything a lesson teaches, as plain text: the body (diagrams left out), the steps, and each quick check's question,
// right answer and explanation.
function lessonText(l) {
  const parts = [plain(String(l.body || '').replace(/<svg[\s\S]*?<\/svg>/gi, ' '))];
  (l.steps || []).forEach(st => parts.push(plain(st.title) + ': ' + plain(st.detail)));
  (l.checks || []).forEach(c => {
    const right = Array.isArray(c.options) && c.options[c.correct] !== undefined ? ' Answer: ' + plain(c.options[c.correct]) + '.' : '';
    parts.push('Quick check: ' + plain(c.question) + right + (c.explanation ? ' ' + plain(c.explanation) : ''));
  });
  return parts.filter(Boolean).join(' ');
}

// Splits text into passages of up to `max` characters, at sentence ends where possible.
function passages(text, max) {
  const sentences = text.match(/[^.!]+[.!]+(?=\s|$)|[^.!]+$/g) || [];   // not at '?', so a quick check keeps its answer
  const out = [];
  let cur = '';
  sentences.forEach(sn => {
    sn = sn.trim();
    if (!sn) return;
    if (cur && (cur + ' ' + sn).length > max) { out.push(cur); cur = ''; }
    cur = cur ? cur + ' ' + sn : sn;
    while (cur.length > max) { out.push(cur.slice(0, max).replace(/\s\S*$/, '')); cur = cur.slice(out[out.length - 1].length).trim(); }
  });
  if (cur) out.push(cur);
  return out;
}

export const ASK_PASSAGE_MAX = 800;   // the Apps Script keeps at most 900 characters of each passage

export function buildAskIndex() {
  const { content, framework } = loadContent();
  const out = [];
  for (const d of Object.keys(DOMAINS)) {
    const fw = framework[d] || {};
    passages(plain(fw.description), ASK_PASSAGE_MAX).forEach(x => out.push({ t: DOMAINS[d] + ' (skill area)', u: 'framework.html#' + d, x }));
    for (const tier of Object.keys(TIERS)) {
      const c = content[d + '-' + tier];
      if (!c || !Array.isArray(c.lessons)) continue;
      c.lessons.forEach((l, i) => {
        const t = String(l.title || 'Lesson ' + (i + 1)).replace(/^Lesson \d+:\s*/, '') + ' · ' + DOMAINS[d] + ' · ' + TIERS[tier];
        passages(lessonText(l), ASK_PASSAGE_MAX).forEach(x => out.push({ t, u: 'lesson.html?course=' + d + '-' + tier + '&lesson=' + (i + 1), x }));
      });
    }
  }
  return out;
}

export function renderAskIndex(items) {
  return '/* Generated by tools/build-search-index.mjs from content/. Do not edit by hand. */\n' +
    'window.PA_ASK = ' + JSON.stringify(items) + ';\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const items = buildIndex();
  fs.writeFileSync(path.join(root, 'search-index.js'), renderIndex(items));
  const ask = buildAskIndex();
  fs.writeFileSync(path.join(root, 'ask-index.js'), renderAskIndex(ask));
  console.log('ask-index.js: ' + ask.length + ' passages');
  console.log('search-index.js: ' + items.length + ' entries (' + items.filter(i => i.k === 'course').length + ' courses, ' + items.filter(i => i.k === 'lesson').length + ' lessons)');
}
